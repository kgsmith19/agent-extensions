"""Generated conformance matrix and its drift guard (#84, phase 3 of #28).

docs/PROVIDER_COMPATIBILITY.md is generated by agent_extensions.sync.matrix. The
committed file must equal render_matrix() exactly, and rendering must not depend
on hash seed or set iteration order.
"""

import os
import subprocess
import sys
from pathlib import Path

import pytest

from agent_extensions.sync import matrix
from agent_extensions.sync.harness import ADAPTERS, KINDS

REPO = Path(__file__).resolve().parents[1]
DOC = REPO / "docs" / "PROVIDER_COMPATIBILITY.md"
HEADER = "Generated by python3 -m agent_extensions.sync.matrix --write; do not hand-edit"
STUBS = ("cline", "kilo", "opencode", "pi")


def _run(args, env=None):
    return subprocess.run(
        [sys.executable, *args], cwd=REPO, env=env, capture_output=True, text=True, check=True
    ).stdout


def test_committed_doc_equals_render_matrix_exactly():
    assert DOC.read_text(encoding="utf-8") == matrix.render_matrix()


def test_generated_header_sits_at_the_top_of_the_doc():
    head = matrix.render_matrix().splitlines()[:3]
    assert any(HEADER in line for line in head)


def test_render_is_stable_within_a_process():
    assert matrix.render_matrix() == matrix.render_matrix()


@pytest.mark.parametrize("seed", ["0", "1", "2", "3"])
def test_render_is_independent_of_hash_seed(seed):
    env = dict(os.environ, PYTHONHASHSEED=seed)
    out = _run(
        ["-c", "import sys; from agent_extensions.sync.matrix import render_matrix; "
               "sys.stdout.write(render_matrix())"],
        env=env,
    )
    assert out == matrix.render_matrix()


def test_module_entrypoint_prints_render_matrix():
    assert _run(["-m", "agent_extensions.sync.matrix"]) == matrix.render_matrix()


def test_main_without_flag_prints_render_matrix(capsys):
    assert matrix.main([]) == 0
    assert capsys.readouterr().out == matrix.render_matrix()


def test_write_flag_writes_render_matrix_to_target(tmp_path, monkeypatch):
    target = tmp_path / "PROVIDER_COMPATIBILITY.md"
    monkeypatch.setattr(matrix, "DOC_PATH", target)
    assert matrix.main(["--write"]) == 0
    assert target.read_text(encoding="utf-8") == matrix.render_matrix()


def test_harness_sections_follow_sorted_registry_order():
    headings = [line for line in matrix.render_matrix().splitlines() if line.startswith("### ")]
    assert headings == [f"### {name}" for name in sorted(ADAPTERS)]


def test_coverage_header_lists_kinds_in_canonical_order():
    lines = matrix.render_matrix().splitlines()
    assert f"| Harness | {' | '.join(KINDS)} |" in lines


def test_stub_coverage_rows_claim_only_skill():
    lines = matrix.render_matrix().splitlines()
    for name in STUBS:
        row = f"| {name} | supported" + " | unsupported" * (len(KINDS) - 1) + " |"
        assert row in lines, name


def test_every_gap_is_named_in_its_harness_section():
    text = matrix.render_matrix()
    sections = text.split("\n### ")[1:]
    for section in sections:
        name = section.split("\n", 1)[0]
        for gap in ADAPTERS[name].gaps():
            assert f"`{gap}`" in section, (name, gap)


@pytest.mark.parametrize("name", STUBS)
def test_stub_sections_state_override_only_detection(name):
    section = matrix.render_matrix().split(f"\n### {name}\n", 1)[1].split("\n### ", 1)[0]
    assert "- Detection: `AE_HARNESS` override only" in section


def test_doc_keeps_hook_bridging_and_stage_references():
    text = matrix.render_matrix()
    assert "## Hook bridging" in text
    assert "bootstrap/hook_env_wrapper.py" in text
    for stage in ("Stage 22", "Stage 23", "Stage 24"):
        assert stage in text
