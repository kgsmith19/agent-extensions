"""Generated provider compatibility matrix (#84, phase 3 of #28).

render_matrix() is the single source of docs/PROVIDER_COMPATIBILITY.md. Its output
depends only on the ADAPTERS registry, KINDS, HARNESS_MARKERS, PROVIDER_ADAPTERS and
fixed prose. Harness rows are sorted by name and kind columns follow KINDS, so the
rendering is deterministic.

Usage:
    python3 -m agent_extensions.sync.matrix           # print the matrix
    python3 -m agent_extensions.sync.matrix --write   # write docs/PROVIDER_COMPATIBILITY.md
"""

import sys
from pathlib import Path
from typing import List, Optional, Sequence, Set

from agent_extensions.sync.harness import (
    ADAPTERS,
    HARNESS_MARKERS,
    KINDS,
    PROVIDER_ADAPTERS,
    canonical_manifest,
)

REPO = Path(__file__).resolve().parents[2]
DOC_PATH = REPO / "docs" / "PROVIDER_COMPATIBILITY.md"

HEADER = "<!-- Generated by python3 -m agent_extensions.sync.matrix --write; do not hand-edit. -->"

_INTRO = (
    "Generated from the harness adapters in `agent_extensions/sync/harness.py`. "
    "Change the adapter or the generator, then run "
    "`python3 -m agent_extensions.sync.matrix --write`."
)

_COVERAGE_PROSE = (
    "Each cell is what the adapter's `capability_report` accepts for that kind: "
    "`supported` or `unsupported`. The `mcp` probe uses stdio transport; a harness that "
    "accepts only some transports names the rest in its gaps."
)

_PRESERVATION_PROSE = (
    "Every adapter's `translate()` keeps every canonical entry. Adapters never add, drop, "
    "or rename a capability; the only per-harness differences are the transport key, the "
    "declared gaps, the import instruction, and the detection markers."
)

_STUB_PROSE = (
    "The stub harnesses (cline, kilo, opencode, pi) claim skills only. They have no "
    "environment marker, are not in the legacy `adapters.PROVIDERS` tuple, and are selected "
    "with `AE_HARNESS=<name>`. Every other kind is a named gap."
)

_HOOK_BRIDGING_PROSE = (
    "Non-Claude providers route hooks via `bootstrap/hook_env_wrapper.py` (which sets "
    "`CLAUDE_PLUGIN_ROOT` and translates the JSON payload). Hook inheritance is declared "
    "unsupported on codex/antigravity — the wrapper bridges invocation, it does not inherit "
    "Claude-native hook semantics. Bulk porting of agent/hook/command definitions is "
    "Stage 22; live conformance canaries are Stage 23; cloud/mobile/web bundles are Stage 24."
)

_REGEN_PROSE = (
    "Regenerate after any adapter change: `python3 -m agent_extensions.sync.matrix --write`. "
    "`python3 -m agent_extensions.sync.matrix` prints the same text without writing. The "
    "drift test in `tests/test_harness_matrix.py` fails when this file is hand-edited."
)


def _probe_manifest() -> dict:
    """One canonical entry per kind; mcp uses stdio, the transport every adapter is probed on."""
    entries = []
    for kind in KINDS:
        entry = {"id": f"capability.probe-{kind}", "kind": kind, "source": f"probe/{kind}"}
        if kind == "mcp":
            entry["transport"] = "stdio"
        entries.append(entry)
    return canonical_manifest(entries)


def _supported_kinds(name: str) -> Set[str]:
    report = ADAPTERS[name].capability_report(_probe_manifest())
    return {
        kind for kind in KINDS if f"capability.probe-{kind}" in report["supported"]
    }


def _detection(name: str) -> str:
    markers = HARNESS_MARKERS.get(name, ())
    if not markers:
        if name == "generic":
            return "fallback when no marker matches; or `AE_HARNESS=generic`"
        return "`AE_HARNESS` override only"
    parts = []
    for var, want in markers:
        parts.append(f"`{var}={want}`" if want is not None else f"`{var}` set")
    return "env " + ", ".join(parts) + "; or `AE_HARNESS=" + name + "`"


def _code_list(items: Sequence[str]) -> str:
    return ", ".join(f"`{item}`" for item in items) if items else "none"


def _coverage_table() -> List[str]:
    header = "| Harness | " + " | ".join(KINDS) + " |"
    divider = "|" + "---|" * (len(KINDS) + 1)
    rows = [header, divider]
    for name in sorted(ADAPTERS):
        supported = _supported_kinds(name)
        cells = ["supported" if kind in supported else "unsupported" for kind in KINDS]
        rows.append(f"| {name} | " + " | ".join(cells) + " |")
    return rows


def _harness_section(name: str) -> List[str]:
    adapter = ADAPTERS[name]
    legacy = {v: k for k, v in PROVIDER_ADAPTERS.items()}.get(name)
    return [
        f"### {name}",
        "",
        f"- Legacy provider key: {f'`{legacy}`' if legacy else 'none (not a legacy provider)'}",
        f"- Detection: {_detection(name)}",
        f"- MCP transport key: {f'`{adapter.transport_key}`' if adapter.transport_key else 'none'}",
        f"- Import: `{adapter.import_instruction}`",
        f"- Gaps: {_code_list(adapter.gaps())}",
        f"- Gap reason: {adapter.gap_reason or 'none'}",
        "",
    ]


def render_matrix() -> str:
    """Return the full Markdown document for docs/PROVIDER_COMPATIBILITY.md."""
    lines: List[str] = [
        HEADER,
        "",
        "# Provider Compatibility Table",
        "",
        _INTRO,
        "",
        "## Capability coverage",
        "",
        _COVERAGE_PROSE,
        "",
        *_coverage_table(),
        "",
        _PRESERVATION_PROSE,
        "",
        "## Harness detail",
        "",
        _STUB_PROSE,
        "",
    ]
    for name in sorted(ADAPTERS):
        lines.extend(_harness_section(name))
    lines.extend([
        "## Hook bridging",
        "",
        _HOOK_BRIDGING_PROSE,
        "",
        "## Regenerating",
        "",
        _REGEN_PROSE,
    ])
    return "\n".join(lines) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if args == ["--write"]:
        DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
        with open(DOC_PATH, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(render_matrix())
        return 0
    if args:
        sys.stderr.write("usage: python3 -m agent_extensions.sync.matrix [--write]\n")
        return 2
    sys.stdout.write(render_matrix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
